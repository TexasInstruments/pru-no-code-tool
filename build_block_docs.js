// ---- run -----------------------------------------------------------------

function main() {
  const blocks = findBlocks(META);
  const results = [];
  for (const b of blocks) {
    try { results.push(buildBlockDocs(b)); }
    catch (e) { console.error(`  FAIL ${b.id}: ${e.message.split('\n')[0]}`); }
  }
  const blockIds = new Set(results.map((r) => r.id));
  let exampleResults = [];
  try { exampleResults = buildExampleDocs(blockIds); }
  catch (e) { console.error(`  examples FAIL: ${e.message.split('\n')[0]}`); }
  const { totalTodo, macroFail } = buildIndex(results, exampleResults);
  console.log(`block-docs: ${results.length}/${blocks.length} blocks × 4 docs + ${exampleResults.length} examples + index -> docs/block-reference/`);
  console.log(`block-docs: ${totalTodo} TODO/VERIFY items; ${results.length - macroFail.length}/${results.length} macros emit cleanly.`);
  if (macroFail.length) console.log(`block-docs: macro did not emit for: ${macroFail.map((r) => r.id).join(', ')}`);
}

main();
