#!/usr/bin/env node
'use strict';
/**
 * generate_block_control_flow_data.js
 *
 * Generates .metadata/sysconfig/.meta/pru_blocks/common/block_control_flow_data.js
 * from scripts/block_control_flow.js so that SysConfig GUI validation can reuse
 * the CI control-flow classifications without hand-typing a table that can drift.
 *
 */
const fs = require('fs');
const path = require('path');
const emit = require('./emit_all_blocks');
const { classify, classifyInstance, boundConfig } = require('./block_control_flow');

const ROOT = path.join(__dirname, '..');
const TARGET = path.join(ROOT, '.metadata', 'sysconfig', '.meta', 'pru_blocks', 'common', 'block_control_flow_data.js');

function generate() {
    const blocks = emit.allBlocks();
    const map = {};
    for (const b of blocks) {
        const res = classify(b.id);
        map[b.id] = res.cls;
    }
    // Continuous by default, sequential once the named config is > 0 (a PWM period count).
    // Listed only when the per-instance classifier positively verifies the bounded configuration.
    const bound = {};
    for (const b of blocks) {
        const cfg = map[b.id] === 'continuous' ? boundConfig(b.id) : null;
        if (cfg && classifyInstance(b.id, { [cfg]: 1 }).cls === 'sequential') bound[b.id] = cfg;
    }

    const keys = Object.keys(map).sort();
    const lines = [];
    lines.push("// Generated by scripts/generate_block_control_flow_data.js — DO NOT EDIT DIRECTLY.");
    lines.push("// Reused by SysConfig GUI validation to source CI block control flow classifications.");
    lines.push("exports = {");
    lines.push("    blockControlFlow: {");
    for (const k of keys) {
        lines.push(`        ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`);
    }
    lines.push("    },");
    lines.push("    blockControlFlowBound: {");
    for (const k of Object.keys(bound).sort()) {
        lines.push(`        ${JSON.stringify(k)}: ${JSON.stringify(bound[k])},`);
    }
    lines.push("    }");
    lines.push("};");
    lines.push("if (typeof module !== 'undefined') {");
    lines.push("    module.exports = exports;");
    lines.push("}");
    lines.push("");

    fs.writeFileSync(TARGET, lines.join("\n"), "utf8");
    console.log(`Generated ${TARGET} (${keys.length} blocks)`);
}

if (require.main === module) {
    generate();
}

module.exports = { generate, TARGET };
