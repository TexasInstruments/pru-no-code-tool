/**
 * emit_block_asm.js - expand a NoCodePRU block macro into a clpru-ready
 * assembly program on stdout. Used by scripts/sim/elf_cosim.py.
 *
 * Usage:
 *   node scripts/sim/emit_block_asm.js <spec.json>
 *
 * spec = {
 *   "block": "ssi_initiator_block",       // block syscfg module name
 *   "subdir": "application_specific",     // pru_blocks subdirectory
 *   "macroCall": "m_ssi_read",            // getMacro() first argument
 *   "macroArgs": {"RES": "R4", ...},      // expansion arguments
 *   "prelude": ["ldi32 R4, 0x1234"],      // optional asm before the macro
 *   "postlude": ["halt"],                 // optional asm after the macro
 *   "labelPrefix": "main",                // entry label (default main)
 *   "macroRepeats": 1,                     // expand the macro this many times
 *   "programCtppr0": true                 // default true: program c28 if used
 * }
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { loadBlockModule, expandMacro, formatAsmLine } = require('../dual_oracle_harness.js');

function main() {
    const specPath = process.argv[2];
    if (!specPath) {
        console.error('usage: node emit_block_asm.js <spec.json>');
        process.exit(2);
    }
    const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));
    const mod = loadBlockModule(spec.block, spec.subdir);
    const opCode = spec.opCode || spec.macroCall;
    const macro = mod.getMacro(spec.macroCall, opCode);
    // expandMacro returns an array of already-parameter-substituted lines
    const repeats = spec.macroRepeats || 1;
    const bodyLines = Array.from({ length: repeats }, () =>
        expandMacro(macro, spec.macroArgs || {})).flat();
    const entry = spec.labelPrefix || 'main';
    // Shared formatAsmLine keeps labels (bare or same-line) in
    // column 1; the old endsWith(':') check indented `label: instr`, which
    // clpru rejects (E0003).
    const fmt = formatAsmLine;
    // C28 = CTPPR0.C28_POINTER << 8 and CTPPR0 resets to 0, so a block
    // that uses c28 needs the same CTPPR0 write the generated firmware performs
    // (pru_blocks_static_module getConstantTableSetup, core icss_g0_pru0 -- the
    // core this harness runs). spec.programCtppr0 === false leaves it out.
    const ctSetup = (spec.programCtppr0 !== false && /\bc28\b/i.test(macro)) ? [
        '    ldi     R28, 0x100',
        '    ldi32   R29, 0x22028',
        '    sbbo    &R28, R29, 0, 4',
    ] : [];
    const lines = [
        '; Auto-generated by emit_block_asm.js',
        '    .text',
        `    .global ${entry}`,
        `${entry}:`,
        ...ctSetup,
        ...(spec.prelude || []).map(fmt),
        ...bodyLines.map(fmt).filter((l) => l !== ''),
        ...(spec.postlude || []).map(fmt),
        '    .end',
        '',
    ];
    process.stdout.write(lines.join('\n'));
}

main();
