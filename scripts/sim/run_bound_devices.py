"""Run a built PRU ELF on TI pru-simulator against the GUI-attached device models.

    python scripts/sim/run_bound_devices.py <elf> <pru_device_bindings.json>
           [--cycles N] [--core pruN] [--decoded-register N]

This is what `gmake sim` runs. The manifest is the one make extracts
from the generated pru_syscfg.asm; every binding in it is instantiated as the
real Python device model and attached to the simulated core's pins.

Exit codes - the verdict is the exit code, and only PASS is 0:
    0  PASS         every attached device was judged and agreed with the firmware
    1  FAIL         something was judged and was wrong
    2  REFUSED      the inputs cannot be run (no/empty manifest, bad ELF, bad core)
    3  NOT CHECKED  the run happened, nothing failed, but at least one device
                    could not be judged (no decoder for its kind, no reader
                    block, result register overwritten). Never reported as a pass.

Which register holds the firmware's decoded value is NOT a property of the
block: SysConfig's register allocator picks it per design. The manifest carries
the allocator's choice for the block that reads each device (`readers`, from
resolveDeviceReaders in the static module). --decoded-register is an explicit
override for hand-built ELFs only.
"""
import os
import argparse
import sys
import re
from pathlib import Path

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

from scripts.sim import device_bindings
from scripts.sim.elf_cosim import find_pru_simulator, _sim_namespace

#: Device kinds whose decoded value this runner can compare with the model.
DECODERS = ("ssi", "bissc")
DEFAULT_CYCLES = 20000

EXIT_PASS, EXIT_FAIL, EXIT_REFUSED, EXIT_NOT_CHECKED = 0, 1, 2, 3


def write_pin_vcd(path, samples, clk_pin, data_pin):
    """Save the real simulator's clock/data pin levels after each PRU cycle."""
    lines = ["$date generated by TI pru-simulator run $end",
             "$version run_bound_devices.py $end", "$timescale 1ns $end",
             "$scope module SSI $end",
             f"$var wire 1 ! CLK_R30_{clk_pin} $end",
             f"$var wire 1 \" DATA_R31_{data_pin} $end",
             "$upscope $end", "$enddefinitions $end", "$dumpvars"]
    prev = None
    for cycle, (gpo, gpi) in enumerate(samples):
        levels = ((gpo >> clk_pin) & 1, (gpi >> data_pin) & 1)
        if cycle == 0:
            lines.extend((f"{levels[0]}!", f"{levels[1]}\"", "$end"))
        elif levels != prev:
            lines.append(f"#{cycle}")
            if levels[0] != prev[0]:
                lines.append(f"{levels[0]}!")
            if levels[1] != prev[1]:
                lines.append(f"{levels[1]}\"")
        prev = levels
    Path(path).write_text("\n".join(lines) + "\n", encoding="ascii")


class NotChecked(Exception):
    """The result register cannot be located. Carries the user-facing reason."""


def parse_register(notation):
    """'R1' -> (1, 0, 4); 'R0.b2' -> (0, 2, 1); 'R3.w1' -> (3, 1, 2)."""
    m = re.fullmatch(r"R(\d+)(?:\.(b|w)(\d))?", notation.strip())
    if not m or int(m.group(1)) > 31:
        raise NotChecked(f"cannot parse result register {notation!r}")
    if m.group(2) == "b":
        byte = int(m.group(3))
        if byte > 3:
            raise NotChecked(f"cannot parse result register {notation!r}")
        return int(m.group(1)), byte, 1
    if m.group(2) == "w":
        word = int(m.group(3))
        if word > 2:
            raise NotChecked(f"cannot parse result register {notation!r}")
        return int(m.group(1)), word, 2
    return int(m.group(1)), 0, 4


def result_register(entry, override):
    """(notation, (reg, byte, width), provenance) for one decoder binding."""
    if override is not None:
        return f"R{override}", (override, 0, 4), "--decoded-register override"
    kind, pin = entry["kind"], entry["primaryPin"]
    readers = entry.get("readers")
    if readers is None:
        raise NotChecked(
            f"the {kind} binding on GPI{pin} carries no reader record, so the "
            f"register holding the decoded value is unknown. Regenerate the "
            f"manifest with SysConfig (gmake syscfg), or pass --decoded-register "
            f"for a hand-built ELF")
    if not readers:
        raise LookupError(
            f"no block in the design reads the {kind} device on GPI{pin} (no "
            f"{kind} reader block has its DATA pin on GPI{pin}), so there is no "
            f"decoded value to check")
    if len(readers) > 1:
        names = ", ".join(r.get("block", "?") for r in readers)
        raise NotChecked(
            f"{len(readers)} blocks read the {kind} device on GPI{pin} ({names}); "
            f"the register left at HALT belongs to at most one of them")
    reader = readers[0]
    notation = reader.get("resultRegister")
    block = reader.get("block", "?")
    if not notation:
        raise NotChecked(f"block {block} reads GPI{pin} but the allocator gave "
                         f"it no output register")
    later = reader.get("laterWriters") or []
    if later:
        raise NotChecked(
            f"{notation} (result of block {block}) is reallocated to later "
            f"block(s) {', '.join(later)} before HALT, so its value at HALT is "
            f"not the read")
    return notation, parse_register(notation), f"block {block}, SysConfig register allocator"


def register_value(registers, where):
    reg, byte, width = where
    return (registers[reg] >> (8 * byte)) & ((1 << (8 * width)) - 1)


def judge_decoder(entry, model, evs, registers, override):
    """Print and judge one ssi/bissc device. Returns 'pass' | 'fail' | 'not checked'."""
    kind = entry["kind"]
    failed = False
    if not evs:
        print("  FAIL: device never produced a frame event")
        if hasattr(model, "get_state"):
            print(f"  Device state: {model.get_state()}")
        failed = True
    try:
        notation, where, provenance = result_register(entry, override)
    except LookupError as exc:
        print(f"  FAIL: {exc}")
        return "fail"
    except NotChecked as exc:
        print(f"  NOT CHECKED: {exc}")
        return "fail" if failed else "not checked"
    print(f"  Result register: {notation} ({provenance})")
    raw = register_value(registers, where)
    expected = getattr(model, "position", None)
    if expected is None:
        expected = model.encoder.position
    if kind == "ssi":
        decoded = raw
    else:
        decoded = (raw >> 8) & ((1 << model.encoder.position_bits) - 1)
    print(f"  Firmware decoded {notation}: {decoded}; model position: {expected}")
    if kind == "bissc" and evs:
        frame = 0
        for bit in model.encoder._bits:
            frame = (frame << 1) | bit
        if raw != frame:
            print(f"  FAIL: firmware frame {raw} differs from model frame {frame}")
            failed = True
    if decoded != expected:
        print("  FAIL: firmware decoded position differs from model")
        failed = True
    return "fail" if failed else "pass"


class DeviceRefused(Exception):
    """A binding cannot be attached to TI pru-simulator. Carries the reason."""


def attach_bound_devices(pru, manifest, sim_dir):
    """Build every binding and attach it to `pru`'s pins. Returns [(entry, model), ...].

    The one attach path: `gmake sim` (main below) and the live browser view
    (live_view.py) both call this, so what the dashboard drives is
    exactly what the headless verdict judged. Raises DeviceRefused, never
    attaches a subset.
    """
    try:
        attached = device_bindings.build_all(manifest, sim_dir)
    except Exception as exc:
        raise DeviceRefused(str(exc)) from exc
    for entry, model in attached:
        # the perif/ models (core.device_model contract: tick()
        # returns a GPI word, no `nets`) cannot sit on TI pru-simulator's
        # DeviceBus, which resolves nets per pin. Refuse by name rather
        # than crash mid-run with an AttributeError.
        if getattr(model, "nets", None) is None:
            raise DeviceRefused(
                f"device kind {entry['kind']!r} "
                f"({type(model).__module__}.{type(model).__name__}) uses the "
                f"core.device_model contract with no `nets`; TI pru-simulator's "
                f"device bus cannot attach it, so gmake sim does not support "
                f"this kind yet")
    for _, model in attached:
        pru.io_port.attach_device(model)
    prime_device_bus(pru, attached)
    return attached


def prime_device_bus(pru, attached):
    """Mask PRU drive off the device-driven pins and settle the idle level.

    A live view repeats this after a core reset: reset clears the bus state and
    the devices' history but keeps them attached.
    """
    driven = set().union(*(device_bindings.driven_pins(model) for _, model in attached))
    device_bus = pru.io_port.device_bus
    device_bus.set_pru_drive_mask(((1 << 20) - 1) & ~sum(1 << pin for pin in driven))
    # Establish the idle clock level before the first PRU edge. The model
    # counts transitions; otherwise its first sample only seeds _prev_ma.
    device_bus.settle(-1, pru.io_port.gpo)


def normalize_core(core):
    """SysConfig core name ('icssg0_pru0', 'rtu_pru1') -> simulator core name."""
    if core and "_" in core:
        match = re.search(r"(?:_|^)(rtu_pru|tx_pru|pru)([01])$", core)
        core = ("rtu" if match.group(1) == "rtu_pru" else
                "tx_pru" if match.group(1) == "tx_pru" else "pru") + match.group(2) if match else core
    return core


def cycle_budget(args, manifest):
    """(budget, provenance). --cycles overrides the manifest's cyclesToSimulate."""
    if args.cycles is not None:
        return args.cycles, "--cycles"
    value = manifest.get("cyclesToSimulate")
    if value is None:
        return DEFAULT_CYCLES, "default; manifest has no cyclesToSimulate"
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise device_bindings.BindingError(
            f"manifest cyclesToSimulate must be a positive integer, got {value!r}")
    return value, "manifest cyclesToSimulate"


def report_run(sim, core, attached, budget, budget_source, decoded_register=None):
    """Print the run's findings and return the verdict exit code.

    The judge shared by `gmake sim` and the live view: everything from the
    clock levels to RESULT. Reads the simulator's current state only.
    """
    pru = sim.cores[core]
    device_bus = pru.io_port.device_bus
    # Where the firmware left each PRU-driven clock. A frame that
    # ends with the clock off its idle level is invisible to the decode
    # (the next transaction simply starts with a phantom edge), so say it.
    for entry, _ in attached:
        if entry.get("clockPin") is not None:
            level = (pru.io_port.gpo >> entry["clockPin"]) & 1
            print(f"Clock R30.{entry['clockPin']} level at end of run: {level}")

    cycles = pru.counters.cycles
    stalls = pru.counters.stall_cycles
    print(f"Cycles: {cycles} (budget: {budget} from {budget_source})")
    print(f"Stalls: {stalls}")
    print(f"Halted: {pru.halted}")

    has_faults = not pru.halted
    not_checked = []
    if not pru.halted:
        print("FAIL: cycle budget exhausted before HALT")
    contentions = list(device_bus.contentions)
    print(f"Bus contentions: {len(contentions)}")
    for contention in contentions:
        print(f"  CONTENTION: {contention}")
    if contentions:
        print(f"FAIL: {len(contentions)} bus contention(s) - the PRU and a "
              f"device drove one push-pull net to opposite levels")
        has_faults = True
    registers = sim.registers(core)
    for entry, model in attached:
        kind = entry["kind"]
        print(f"\nDevice {kind} on GPI{entry['primaryPin']}:")
        faults = getattr(model, "faults", lambda: [])()
        if faults:
            has_faults = True
            print("  FAULTS:")
            for f in faults:
                print(f"    - {f}")
        else:
            print("  FAULTS: None")

        if hasattr(model, "count"):
            print(f"  Count: {model.count}")
        if hasattr(model, "pos"):
            print(f"  Position: {model.pos}")
        if hasattr(model, "position"):
            print(f"  Model position: {model.position}")
        if hasattr(model, "frames"):
            frames = model.frames
            if callable(frames):
                frames = frames()
            if isinstance(frames, int):
                # e.g. UartTransmitter: a configured repeat count, not a log.
                print(f"  Frames configured: {frames}")
            else:
                print(f"  Frames: {len(frames)}")

        evs = model.events() if hasattr(model, "events") else []
        print(f"  Events: {len(evs)}")

        if kind in DECODERS:
            verdict = judge_decoder(entry, model, evs, registers, decoded_register)
            if verdict == "fail":
                has_faults = True
            elif verdict == "not checked":
                not_checked.append(kind)
        else:
            if not evs:
                print("  Device recorded no frame/activity event")
            print(f"  NOT CHECKED: no decoder for kind {kind}; this run is "
                  f"not a verdict on the firmware")
            not_checked.append(kind)

    # Also print registers so tests can assert decoded values!
    print("\nRegisters:")
    for i, reg in enumerate(sim.registers(core)):
        print(f"  R{i}: {reg}")

    if has_faults:
        print("\nRESULT: FAIL")
        return EXIT_FAIL
    if not_checked:
        print(f"\nRESULT: NOT CHECKED ({', '.join(not_checked)}) - not a pass")
        return EXIT_NOT_CHECKED
    print("\nRESULT: PASS")
    return EXIT_PASS


def main(argv=None):
    ap = argparse.ArgumentParser(description="Run built ELF against device models")
    ap.add_argument("elf", help="Path to compiled ELF (.out)")
    ap.add_argument("manifest", help="Path to pru_device_bindings.json")
    ap.add_argument("--cycles", type=int, default=None,
                    help="Cycle budget; overrides the manifest's cyclesToSimulate "
                         f"(default when neither is given: {DEFAULT_CYCLES})")
    ap.add_argument("--core", help="Override the SysConfig core in the manifest")
    ap.add_argument("--decoded-register", type=int,
                    help="Explicit override of the register holding the decoded "
                         "value, for hand-built ELFs. A SysConfig build carries "
                         "the allocator's choice in the manifest.")
    ap.add_argument("--vcd", help="Write CLK/DATA pin waveform from the TI simulator")
    args = ap.parse_args(argv)

    try:
        manifest = device_bindings.load_manifest(args.manifest)
        budget, budget_source = cycle_budget(args, manifest)
    except device_bindings.BindingError as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return EXIT_REFUSED

    bindings = manifest.get("bindings", [])
    if not bindings:
        print("REFUSED: manifest has no device bindings. An empty manifest is REFUSED.", file=sys.stderr)
        return EXIT_REFUSED

    sim_dir = find_pru_simulator()

    with _sim_namespace(sim_dir):
        from simulator import Simulator

        sim = Simulator(os.path.join(sim_dir, "memory.cfg"))
        from tools.headless_runner import _validate_linked_elf
        core = normalize_core(args.core or manifest.get("core"))
        if not core or core not in sim.cores:
            print(f"REFUSED: unknown or absent PRU core {core!r}", file=sys.stderr)
            return EXIT_REFUSED
        with open(args.elf, "rb") as f:
            elf_data = f.read()
        try:
            entry_pc = _validate_linked_elf(elf_data)
        except ValueError as exc:
            print(f"REFUSED: invalid linked ELF: {exc}", file=sys.stderr)
            return EXIT_REFUSED
        errors = sim.load_elf(core, elf_data)
        if errors:
            print(f"ELF load errors: {errors}", file=sys.stderr)
            return EXIT_FAIL

        pru = sim.cores[core]
        pru.pc = entry_pc

        try:
            attached = attach_bound_devices(pru, manifest, sim_dir)
        except DeviceRefused as exc:
            print(f"REFUSED: {exc}", file=sys.stderr)
            return EXIT_REFUSED

        print(f"Attached {len(attached)} devices")
        samples = []
        if args.vcd:
            samples.append((pru.io_port.gpo, pru.io_port.gpi))
        for step in range(budget):
            sim.step(core, 1)
            if args.vcd:
                samples.append((pru.io_port.gpo, pru.io_port.gpi))
            if pru.halted:
                break

        if args.vcd:
            first = next((entry for entry, _ in attached if entry["kind"] == "ssi"), None)
            if first is not None:
                write_pin_vcd(args.vcd, samples, first["clockPin"], first["primaryPin"])
                print(f"VCD: {args.vcd} (CLK R30.{first['clockPin']}, DATA R31.{first['primaryPin']})")

        return report_run(sim, core, attached, budget, budget_source,
                          args.decoded_register)


if __name__ == "__main__":
    sys.exit(main())
